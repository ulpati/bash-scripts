ascii_banner() {
cat << "EOF"
 _     _  __         ____
| |   (_)/ _| ___   / ___| __ _ _ __ ___   ___
| |   | | |_ / _ \ | |  _ / _` | '_ ` _ \ / _ \
| |___| |  _|  __/ | |_| | (_| | | | | | |  __/
|_____|_|_|  \___|  \____|\__,_|_| |_| |_|\___|

EOF
}

ascii_section() {
    echo "================================="
    echo "     $1"
    echo "================================="
}

ascii_trophy() {
cat << "EOF"
       ___________
      '._==_==_=_.'
      .-\:      /-.
     | (|:.     |) |
      '-|:.     |-'
        \::.    /
         '::. .'
           ) (
         _.' '._
        `"""""""`

EOF
}

ascii_fire() {
cat << "EOF"
    (  )
   ( )(
    ) (
  /-----\
 (       )
  `-----`

EOF
}

ascii_exit() {
cat << "EOF"
 ____                                _
/ ___|  ___  ___   _   _  ___  _   _| |
\___ \ / _ \/ _ \ | | | |/ _ \| | | | |
 ___) |  __/  __/ | |_| | (_) | |_| |_|
|____/ \___|\___|  \__, |\___/ \__,_(_)
                   |___/

EOF
}
